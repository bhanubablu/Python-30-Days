# +    Addition
# -    Subtraction
# *    Multiplication
# /    Division
# //   Floor division
# %    Modulus (remainder)
# **   Power

#Normal division /
# Normal division / gives a decimal result:
# print(10 / 3)  Output: 3.3333333333333335

# Floor division //
# Floor division // gives the whole-number part:
# print(10 // 3)   Output: 3

# % — Modulus
# % gives the remainder after division.
# print(10 % 3) 10 ÷ 3 gives remainder 1, so: Output: 1

# ** — Power
# print(2 ** 3) means: 2 × 2 × 2 = 8 output: 8

a = 10
b = 3

# Arthematic operations
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Remainder:", a % b)
print("Power:", a ** b)

# Assingment operator
score = 10 
score += 5
print("score:", score)




